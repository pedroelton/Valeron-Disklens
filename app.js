/* --------------------------------------------------------------- polling */

function phaseLabel(s) {
  if (s.phase === "Aggregating folders") return t("status.aggregating");
  if (s.phase === "Measuring known cleanup targets") return t("status.measuring");
  if (s.status === "hashing") return t("status.hashing");
  return t("status.scanning");
}

function setProgress(s) {
  const running = s.status === "scanning" || s.status === "hashing";
  $("progress").hidden = !running;
  $("scanBtn").disabled = running;
  $("cancelBtn").hidden = !running;
  if (!running) return;

  const bar = document.querySelector(".bar");
  if (s.status === "hashing" && s.dup_total) {
    bar.classList.remove("indeterminate");
    $("progressFill").style.width = Math.round((s.dup_done / s.dup_total) * 100) + "%";
  } else {
    bar.classList.add("indeterminate");
  }
  $("progressPhase").textContent = phaseLabel(s);
  $("progressStats").textContent = t("stats.line", {
    files: num(s.files), size: fmt(s.bytes), dirs: num(s.dirs), sec: Math.round(s.elapsed || 0),
  });
  $("progressPath").textContent = s.current || "";
}

let lastStatus = "";
async function poll() {
  try {
    const s = await api("/api/status");
    if (s.error) return;
    setProgress(s);
    if (s.status !== lastStatus) {
      if (s.status === "done") {
        const r = await api("/api/results");
        render(r);
        const total = (r.junk_safe_total || 0) + (r.junk_careful_total || 0) +
                      (r.dup_waste || 0) + (r.project_junk_total || 0);
        toast(t("toast.done", { size: fmt(total) }));
      } else if (s.status === "error") {
        toast(t("toast.error", { msg: esc(s.message) }));
      } else if (s.status === "cancelled") {
        toast(t("toast.cancelled"));
      }
      lastStatus = s.status;
    }
  } catch (e) { /* server stopped, ignore */ }
}

/* ---------------------------------------------------------------- actions */

function confirmDelete(mode) {
  const paths = [...state.selection.keys()];
  const contents = paths.filter((p) => state.selection.get(p).contentsOnly);
  let total = 0;
  state.selection.forEach((v) => { total += v.size || 0; });

  $("modalTitle").textContent = mode === "trash" ? t("modal.trashtitle") : t("modal.permtitle");
  $("modalText").innerHTML = mode === "trash"
    ? t("modal.trashtext", { n: paths.length, size: fmt(total) })
    : t("modal.permtext", { n: paths.length, size: fmt(total) });
  $("modalList").innerHTML = paths
    .map((p) => esc(p) + (state.selection.get(p).contentsOnly ? "  " + t("modal.contents") : ""))
    .join("<br>");
  $("modal").hidden = false;

  $("modalOk").onclick = async () => {
    $("modal").hidden = true;
    const res = await api("/api/delete", { paths, mode, contents_only: contents });
    if (res.error) { toast(errText(res.error)); return; }

    let msg = t("toast.freed", { size: fmt(res.freed || 0), n: (res.deleted || []).length });
    const fails = res.failed || [];
    if (fails.length) {
      const list = fails.slice(0, 3).map((f) => esc(f.path) + " (" + errText(f.error) + ")").join(" | ");
      msg += "<br><span class='dim'>" + t("toast.failed", { n: fails.length, list }) + "</span>";
    } else if (mode === "trash") {
      msg += "<br><span class='dim'>" + t("toast.trashnote") + "</span>";
    }
    toast(msg);

    (res.deleted || []).forEach((p) => {
      document.querySelectorAll(`[data-rowpath="${CSS.escape(p)}"]`).forEach((el) => el.remove());
      state.selection.delete(p);
    });
    renderActionBar();
    refreshDisk();
  };
}

async function refreshDisk() {
  const info = await api("/api/info");
  const root = state.results ? state.results.root : "";
  const hit = (info.drives || []).find((x) => root.toUpperCase().startsWith(x.path.toUpperCase()));
  if (hit && state.results) {
    state.results.disk = { total: hit.total, used: hit.used, free: hit.free };
    $("freeVal").textContent = fmt(hit.free);
    $("usedVal").textContent = fmt(hit.used);
  }
}

function setAdminFlag(admin) {
  const flag = $("adminFlag");
  flag.textContent = admin ? t("admin.yes") : t("admin.no");
  flag.className = "flag " + (admin ? "admin" : "noadmin");
}

