async function init() {
  LANG = detectLang();
  applyI18n();

  const info = await api("/api/info");
  state.info = info;

  const sel = $("driveSelect");
  sel.innerHTML = (info.drives || [])
    .map((x) => `<option value="${esc(x.path)}">${esc(x.path)}  ${fmt(x.free)} / ${fmt(x.total)}</option>`)
    .join("");
  $("pathInput").value = info.default || "";
  sel.value = info.default;
  sel.addEventListener("change", () => { $("pathInput").value = sel.value; });
  $("minDup").value = info.min_dup_mb || 5;
  setAdminFlag(info.admin);

  if (!info.windows) $("recycleBtn").hidden = true;
  if (!info.allow_permanent) {
    $("delPerm").disabled = true;
    $("delPerm").title = t("bar.permoff");
  }

  $("scanBtn").addEventListener("click", async () => {
    clearSelection();
    lastStatus = "";
    const res = await api("/api/scan", {
      path: $("pathInput").value.trim(),
      min_dup_mb: Number($("minDup").value) || 5,
    });
    if (res.error) toast(errText(res.error) + (res.detail ? ": " + esc(res.detail) : ""));
  });

  $("cancelBtn").addEventListener("click", () => api("/api/cancel", {}));

  $("recycleBtn").addEventListener("click", async () => {
    const res = await api("/api/empty-recycle", {});
    toast(res.error ? t("toast.binerror", { msg: esc(res.error) }) : t("toast.binempty"));
    refreshDisk();
  });

  $("helpBtn").addEventListener("click", () => { $("help").hidden = false; });
  $("helpClose").addEventListener("click", () => {
    $("help").hidden = true;
    try { localStorage.setItem("disklens_help_seen", "1"); } catch (e) { /* ignore */ }
  });

  $("langBtn").addEventListener("click", () => {
    LANG = LANG === "pt" ? "en" : "pt";
    try { localStorage.setItem("disklens_lang", LANG); } catch (e) { /* ignore */ }
    applyI18n();
  });

  document.querySelectorAll(".tab").forEach((tb) => {
    tb.addEventListener("click", () => {
      document.querySelectorAll(".tab").forEach((x) => x.classList.remove("active"));
      document.querySelectorAll(".panel").forEach((x) => x.classList.remove("active"));
      tb.classList.add("active");
      $("tab-" + tb.dataset.tab).classList.add("active");
    });
  });

  $("dirFilter").addEventListener("input", () => state.results && renderDirs());
  $("dirDepth").addEventListener("change", () => state.results && renderDirs());
  $("fileFilter").addEventListener("input", () => state.results && renderFiles());

  $("selectDups").addEventListener("click", () => {
    document.querySelectorAll("#dupList input[type=checkbox][data-dup]").forEach((cb) => {
      if (!cb.checked) {
        cb.checked = true;
        cb.closest(".row").classList.add("selected");
        toggleSelect(cb.dataset.path, Number(cb.dataset.size), false, true);
      }
    });
  });

  $("clearSel").addEventListener("click", clearSelection);
  $("delTrash").addEventListener("click", () => confirmDelete("trash"));
  $("delPerm").addEventListener("click", () => confirmDelete("permanent"));
  $("modalCancel").addEventListener("click", () => { $("modal").hidden = true; });

  document.addEventListener("keydown", (e) => {
    if (e.key === "Escape") { $("modal").hidden = true; $("help").hidden = true; }
  });

  let seen = null;
  try { seen = localStorage.getItem("disklens_help_seen"); } catch (e) { /* ignore */ }
  if (!seen) $("help").hidden = false;

  setInterval(poll, 900);
  poll();
}

