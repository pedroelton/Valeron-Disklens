let LANG = "en";

function t(key, params) {
  let s = (I18N[LANG] && I18N[LANG][key]) || I18N.en[key] || key;
  if (params) {
    Object.keys(params).forEach((k) => { s = s.split("{" + k + "}").join(params[k]); });
  }
  return s;
}

function detectLang() {
  let saved = null;
  try { saved = localStorage.getItem("disklens_lang"); } catch (e) { /* ignore */ }
  if (saved === "pt" || saved === "en") return saved;
  return (navigator.language || "en").toLowerCase().startsWith("pt") ? "pt" : "en";
}

function applyI18n() {
  document.documentElement.lang = LANG === "pt" ? "pt-BR" : "en";
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPh);
  });
  $("langBtn").textContent = t("lang.other");
  $("riskLegend").innerHTML = t("legend.risk");
  if (state.info) setAdminFlag(state.info.admin);
  if (state.results) render(state.results);
  renderActionBar();
  renderHelp();
}

/* ------------------------------------------------------------------ utils */

function fmt(bytes) {
  const b = Number(bytes) || 0;
  if (b >= 1024 ** 4) return (b / 1024 ** 4).toFixed(2) + " TB";
  if (b >= 1024 ** 3) return (b / 1024 ** 3).toFixed(1) + " GB";
  if (b >= 1024 ** 2) return (b / 1024 ** 2).toFixed(0) + " MB";
  if (b >= 1024) return (b / 1024).toFixed(0) + " KB";
  return b + " B";
}

function num(n) {
  return (Number(n) || 0).toLocaleString(LANG === "pt" ? "pt-BR" : "en-US");
}

function fmtDate(ts) {
  if (!ts) return "";
  return new Date(ts * 1000).toLocaleDateString(LANG === "pt" ? "pt-BR" : "en-US",
    { year: "numeric", month: "2-digit", day: "2-digit" });
}

function esc(s) {
  return String(s).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));
}

function errText(code) {
  const key = "err." + code;
  const translated = t(key);
  return translated === key ? code : translated;
}

async function api(route, body) {
  const opts = { headers: { "X-DiskLens-Token": TOKEN } };
  if (body) {
    opts.method = "POST";
    opts.headers["Content-Type"] = "application/json";
    opts.body = JSON.stringify(body);
  }
  const res = await fetch(route, opts);
  return res.json();
}

let toastTimer = null;
function toast(html) {
  const el = $("toast");
  el.innerHTML = html;
  el.hidden = false;
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => { el.hidden = true; }, 7000);
}

function openPath(path) { api("/api/open", { path }); }

/* -------------------------------------------------------------- selection */

function toggleSelect(path, size, contentsOnly, checked) {
  if (checked) state.selection.set(path, { size, contentsOnly: !!contentsOnly });
  else state.selection.delete(path);
  renderActionBar();
}

function renderActionBar() {
  const n = state.selection.size;
  $("actionbar").hidden = n === 0;
  let total = 0;
  state.selection.forEach((v) => { total += v.size || 0; });
  $("selCount").textContent = n;
  $("selSize").textContent = fmt(total);
}

function clearSelection() {
  state.selection.clear();
  document.querySelectorAll("input[type=checkbox][data-path]").forEach((c) => { c.checked = false; });
  document.querySelectorAll(".row.selected").forEach((r) => r.classList.remove("selected"));
  renderActionBar();
}

/* ------------------------------------------------------------------- rows */

function rowHTML(path, size, max, opts = {}) {
  const pct = max > 0 ? Math.max(1, Math.round((size / max) * 100)) : 0;
  const sub = opts.sub ? `<small>${esc(opts.sub)}</small>` : "";
  const box = opts.noCheck
    ? '<span class="dim mono">-</span>'
    : `<input type="checkbox" data-path="${esc(path)}" data-size="${size}" data-contents="${opts.contentsOnly ? 1 : 0}">`;
  return `<div class="row" data-rowpath="${esc(path)}">
      ${box}
      <div class="path" title="${esc(path)} (${t("files.dblclick")})">${esc(opts.label || path)}${opts.badge || ""}${sub}</div>
      <div class="meter"><i style="width:${pct}%"></i></div>
      <div class="size">${fmt(size)}</div>
    </div>`;
}

function bindRows(container) {
  container.querySelectorAll("input[type=checkbox][data-path]").forEach((cb) => {
    cb.addEventListener("change", () => {
      cb.closest(".row").classList.toggle("selected", cb.checked);
      toggleSelect(cb.dataset.path, Number(cb.dataset.size), cb.dataset.contents === "1", cb.checked);
    });
  });
  container.querySelectorAll(".path").forEach((p) => {
    p.addEventListener("dblclick", () => openPath(p.closest(".row").dataset.rowpath));
  });
}

function fillList(el, items, mapper, emptyMsg) {
  if (!items || !items.length) {
    el.innerHTML = `<div class="emptystate">${esc(emptyMsg)}</div>`;
    return;
  }
  const max = Math.max(...items.map((i) => i.size || 0));
  el.innerHTML = items.map((i) => mapper(i, max)).join("");
  bindRows(el);
}

/* ----------------------------------------------------------------- render */

function render(r) {
  state.results = r;
  $("welcome").hidden = true;
  $("app").hidden = false;

  const disk = r.disk || { total: 0, used: 0, free: 0 };
  $("bandRoot").textContent = r.root;
  $("freeVal").textContent = fmt(disk.free);
  $("totalVal").textContent = fmt(disk.total);
  $("usedVal").textContent = fmt(disk.used);

  const p = {
    safe: r.junk_safe_total || 0,
    careful: r.junk_careful_total || 0,
    dup: r.dup_waste || 0,
    proj: r.project_junk_total || 0,
  };
  p.reclaim = p.safe + p.careful + p.dup + p.proj;
  $("reclaimVal").textContent = fmt(p.reclaim);

  renderStack(disk, p);
  renderVerdicts(r, disk, p);
  renderLevel1(r);
  renderExt(r);
  renderJunk(r);
  renderProjectJunk(r);
  renderDirs();
  renderFiles();
  renderDups(r);
  renderOld(r);
}

function renderStack(disk, p) {
  const rest = Math.max(0, disk.used - p.safe - p.careful - p.dup - p.proj);
  const segs = [
    { label: t("risk.safe"), v: p.safe, c: "#4fae6c" },
    { label: t("risk.careful"), v: p.careful, c: "#d98c1f" },
    { label: t("tab.dups"), v: p.dup, c: "#f5a800" },
    { label: t("clean.project"), v: p.proj, c: "#8e6bbf" },
    { label: t("band.used"), v: rest, c: "#3a3a3a" },
    { label: t("band.free"), v: disk.free, c: "#151515" },
  ].filter((s) => s.v > 0);
  const total = disk.total || segs.reduce((a, s) => a + s.v, 0) || 1;
  $("stack").innerHTML = segs
    .map((s) => `<div style="width:${(s.v / total) * 100}%;background:${s.c}" title="${esc(s.label)}: ${fmt(s.v)}"></div>`)
    .join("");
  $("stackLegend").innerHTML = segs
    .map((s) => `<span><i style="background:${s.c}"></i>${esc(s.label)} <b class="mono">${fmt(s.v)}</b></span>`)
    .join("");
}

function renderVerdicts(r, disk, p) {
  const pctFree = disk.total ? (disk.free / disk.total) * 100 : 0;
  const notScanned = Math.max(0, disk.used - (r.root_total || 0));
  const cards = [
    {
      label: t("verdict.situation"),
      kpi: t("verdict.free", { pct: pctFree.toFixed(1) }),
      text: pctFree < 5 ? t("verdict.critical") : pctFree < 10 ? t("verdict.tight") : t("verdict.fine"),
    },
    {
      label: t("verdict.quickwin"),
      kpi: fmt(p.reclaim),
      text: t("verdict.quickwintext", { safe: fmt(p.safe), dup: fmt(p.dup), proj: fmt(p.proj) }),
    },
    {
      label: t("verdict.unaccounted"),
      kpi: fmt(notScanned),
      text: notScanned > 5 * 1024 ** 3 ? t("verdict.unaccountedbig") : t("verdict.unaccountedsmall"),
    },
    {
      label: t("verdict.analyzed"),
      kpi: num(r.files),
      text: t("verdict.analyzedtext", { dirs: num(r.dirs), errors: num(r.errors) }),
    },
  ];

  const topDir = (r.top_dirs || []).find((d) => d.depth >= 1 && d.depth <= 2);
  if (topDir) cards.push({ label: t("verdict.biggestdir"), kpi: fmt(topDir.size), text: topDir.path });
  const topFile = (r.top_files || [])[0];
  if (topFile) cards.push({ label: t("verdict.biggestfile"), kpi: fmt(topFile.size), text: topFile.path });

  $("verdicts").innerHTML = cards
    .map((c) => `<div class="card">
        <div class="label">${esc(c.label)}</div>
        <div class="kpi">${esc(c.kpi)}</div>
        <p>${esc(c.text)}</p>
      </div>`)
    .join("");
}

function junkText(j) {
  if (LANG === "pt" && JUNK_PT[j.id]) return { name: JUNK_PT[j.id][0], note: JUNK_PT[j.id][1] };
  return { name: j.name, note: j.note };
}

function renderLevel1(r) {
  fillList($("level1"), (r.top_dirs || []).filter((d) => d.depth === 1).slice(0, 12),
    (d, max) => rowHTML(d.path, d.size, max, { sub: num(d.files) + " " + t("tab.files").toLowerCase() }),
    t("dirs.empty"));
}

function renderExt(r) {
  const items = (r.by_ext || []).slice(0, 12).map((e) => ({ path: e.ext, size: e.size, files: e.files }));
  fillList($("byExt"), items,
    (e, max) => rowHTML(e.path, e.size, max, { noCheck: true, sub: num(e.files) + " " + t("tab.files").toLowerCase() }),
    t("dirs.empty"));
}

function renderJunk(r) {
  const junk = r.junk || [];
  const real = junk.filter((j) => j.kind !== "info" && j.exists && j.size > 0);
  const info = junk.filter((j) => j.kind === "info");
  const max = Math.max(1, ...real.map((j) => j.size));

  let html = real.map((j) => {
    const txt = junkText(j);
    const badge = `<span class="riskbadge r-${j.risk}">${t("risk." + j.risk)}</span>`;
    return j.resolved.map((res, idx) =>
      rowHTML(res.path, res.size, max, {
        label: idx === 0 ? txt.name : txt.name + " (" + (idx + 1) + ")",
        badge: idx === 0 ? badge : "",
        sub: idx === 0 ? txt.note + "  ·  " + res.path : res.path,
        contentsOnly: j.kind === "contents",
      })).join("");
  }).join("");

  if (!html) html = `<div class="emptystate">${esc(t("clean.empty"))}</div>`;

  html += info.map((j) => {
    const txt = junkText(j);
    const size = j.size ? ` <b class="mono accent">${fmt(j.size)}</b>` : "";
    return `<div class="row" data-rowpath="${esc(j.path || "")}">
        <span class="dim mono">i</span>
        <div class="path">${esc(txt.name)}<span class="riskbadge r-info">${t("risk.info")}</span>${size}
          <small>${esc(txt.note)}</small></div>
        <div class="meter"></div>
        <div class="size">${j.size ? fmt(j.size) : "-"}</div>
      </div>`;
  }).join("");

  $("junkList").innerHTML = html;
  bindRows($("junkList"));
}

function renderProjectJunk(r) {
  fillList($("projectJunk"), r.project_junk || [], (d, max) => {
    const pair = PROJECT_KIND[d.kind] || ["", ""];
    return rowHTML(d.path, d.size, max, { sub: LANG === "pt" ? pair[1] : pair[0] });
  }, t("clean.projectempty"));
}

function renderDirs() {
  const r = state.results;
  const q = $("dirFilter").value.toLowerCase();
  const depth = Number($("dirDepth").value);
  let items = r.top_dirs || [];
  if (q) items = items.filter((d) => d.path.toLowerCase().includes(q));
  if (depth) items = items.filter((d) => d.depth === depth);
  fillList($("dirList"), items.slice(0, 150),
    (d, max) => rowHTML(d.path, d.size, max, { sub: num(d.files) + " " + t("tab.files").toLowerCase() }),
    t("dirs.empty"));
}

function renderFiles() {
  const r = state.results;
  const q = $("fileFilter").value.toLowerCase();
  let items = r.top_files || [];
  if (q) items = items.filter((f) => f.path.toLowerCase().includes(q));
  fillList($("fileList"), items.slice(0, 200),
    (f, max) => rowHTML(f.path, f.size, max, { sub: t("files.modified") + " " + fmtDate(f.mtime) }),
    t("files.empty"));
}

function renderDups(r) {
  const groups = r.duplicates || [];
  $("dupSummary").textContent = groups.length
    ? t("dups.summary", { n: groups.length, size: fmt(r.dup_waste) })
    : "";
  if (!groups.length) {
    $("dupList").innerHTML = `<div class="emptystate">${esc(t("dups.empty"))}</div>`;
    return;
  }
  $("dupList").innerHTML = groups.map((g, gi) => {
    const rows = g.paths.map((p, i) => {
      const tag = i === 0 ? `<span class="keep">${t("dups.keep")}</span>` : "";
      const box = i === 0
        ? '<span class="dim mono">-</span>'
        : `<input type="checkbox" data-path="${esc(p)}" data-size="${g.size}" data-contents="0" data-dup="1">`;
      return `<div class="row" data-rowpath="${esc(p)}">
          ${box}
          <div class="path" title="${esc(p)}">${esc(p)} ${tag}</div>
          <div class="size">${fmt(g.size)}</div>
        </div>`;
    }).join("");
    return `<div class="dupgroup">
        <header>
          <span>${t("dups.copies", { n: g.paths.length })} · ${t("dups.each", { size: fmt(g.size) })} · ${t("dups.match")} ${t("dups." + g.confidence)}</span>
          <span class="accent mono">${t("dups.waste")} ${fmt(g.waste)}</span>
        </header>${rows}</div>`;
  }).join("");
  bindRows($("dupList"));
}

function renderOld(r) {
  fillList($("oldList"), r.old_files || [],
    (f, max) => rowHTML(f.path, f.size, max, { sub: t("files.lastmod") + " " + fmtDate(f.mtime) }),
    t("old.empty"));
}

